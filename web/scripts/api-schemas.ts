/**
 * zod schemas from the API's OpenAPI document (#16, ADR 0021).
 *
 * Pure (no Node APIs) so the freshness test can run it in Vitest; the CLI is
 * generate-api-schemas.ts. Covers the JSON Schema that Pydantic emits for the
 * response models: objects, arrays, records, enums, consts, nullable unions and
 * discriminated unions.
 */

type Schema = { [key: string]: unknown }

export type OpenApiDocument = {
  components: { schemas: Record<string, Schema> }
}

const REF_PREFIX = '#/components/schemas/'

const HEADER = `// Generated by web/scripts/generate-api-schemas.ts from
// server/lamathek/domain/openapi.json. Do not edit: change the Pydantic models in
// server/lamathek/contract/models.py, run \`lamathek openapi\` and \`npm run generate:api\`.
import { z } from 'zod'
`

export function schemaConstName(component: string): string {
  return `${component.charAt(0).toLowerCase()}${component.slice(1)}Schema`
}

function refName(ref: unknown): string {
  if (typeof ref !== 'string' || !ref.startsWith(REF_PREFIX)) {
    throw new Error(`Unsupported $ref: ${String(ref)}`)
  }
  return ref.slice(REF_PREFIX.length)
}

function literal(value: unknown): string {
  if (typeof value === 'string') return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
  return JSON.stringify(value)
}

function propertyKey(name: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(name) ? name : literal(name)
}

function docComment(description: unknown, pad: string): string {
  if (typeof description !== 'string' || !description.trim()) return ''
  const text = description
    .replace(/``/g, '`')
    .replace(/\*\//g, '* /')
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
    .join(' ')
  return `${pad}/** ${text} */\n`
}

function asSchemas(value: unknown): Schema[] {
  if (!Array.isArray(value)) throw new Error(`Expected a list of schemas: ${JSON.stringify(value)}`)
  return value as Schema[]
}

function zodObject(schema: Schema, depth: number): string {
  const properties = (schema.properties ?? {}) as Record<string, Schema>
  const names = Object.keys(properties)
  if (names.length === 0) {
    const extra = schema.additionalProperties
    if (extra === undefined || extra === true) return 'z.record(z.string(), z.unknown())'
    if (extra === false) return 'z.object({})'
    return `z.record(z.string(), ${zodExpression(extra as Schema, depth)})`
  }
  const required = new Set((schema.required ?? []) as string[])
  const pad = '  '.repeat(depth + 1)
  const lines = names.map((name) => {
    const property = properties[name]!
    let expression = zodExpression(property, depth + 1)
    if (!required.has(name)) {
      expression += 'default' in property ? `.default(${literal(property.default)})` : '.optional()'
    }
    return `${docComment(property.description, pad)}${pad}${propertyKey(name)}: ${expression},`
  })
  return `z.object({\n${lines.join('\n')}\n${'  '.repeat(depth)}})`
}

function zodExpression(schema: Schema, depth = 0): string {
  if ('$ref' in schema) return schemaConstName(refName(schema.$ref))
  if ('oneOf' in schema && schema.discriminator) {
    const { propertyName } = schema.discriminator as { propertyName: string }
    const options = asSchemas(schema.oneOf).map((option) => zodExpression(option, depth))
    return `z.discriminatedUnion(${literal(propertyName)}, [${options.join(', ')}])`
  }
  const union = schema.anyOf ?? schema.oneOf
  if (union !== undefined) {
    const options = asSchemas(union)
    const present = options.filter((option) => option.type !== 'null')
    const inner =
      present.length === 1
        ? zodExpression(present[0]!, depth)
        : `z.union([${present.map((option) => zodExpression(option, depth)).join(', ')}])`
    return present.length < options.length ? `${inner}.nullable()` : inner
  }
  if ('const' in schema) return `z.literal(${literal(schema.const)})`
  if (Array.isArray(schema.enum)) {
    if (!schema.enum.every((value) => typeof value === 'string')) {
      throw new Error(`Only string enums are supported: ${JSON.stringify(schema.enum)}`)
    }
    return `z.enum([${schema.enum.map(literal).join(', ')}])`
  }
  switch (schema.type) {
    case 'string':
      return 'z.string()'
    case 'integer':
      return 'z.number().int()'
    case 'number':
      return 'z.number()'
    case 'boolean':
      return 'z.boolean()'
    case 'null':
      return 'z.null()'
    case 'array':
      return `z.array(${zodExpression(schema.items as Schema, depth)})`
    case 'object':
      return zodObject(schema, depth)
  }
  if (Object.keys(schema).every((key) => key === 'description')) return 'z.unknown()'
  throw new Error(`Unsupported schema: ${JSON.stringify(schema)}`)
}

function collectRefs(node: unknown, found: Set<string>): Set<string> {
  if (Array.isArray(node)) {
    for (const item of node) collectRefs(item, found)
  } else if (node && typeof node === 'object') {
    for (const [key, value] of Object.entries(node)) {
      if (key === '$ref') found.add(refName(value))
      else collectRefs(value, found)
    }
  }
  return found
}

/** Component names, each after the components it refers to. */
function dependencyOrder(schemas: Record<string, Schema>): string[] {
  const ordered: string[] = []
  const state = new Map<string, 'visiting' | 'done'>()
  const visit = (name: string, path: string[]) => {
    if (state.get(name) === 'done') return
    if (state.get(name) === 'visiting') {
      throw new Error(`Recursive schemas are not supported: ${[...path, name].join(' → ')}`)
    }
    if (!(name in schemas)) throw new Error(`Unknown component: ${name}`)
    state.set(name, 'visiting')
    for (const dependency of [...collectRefs(schemas[name], new Set())].sort()) {
      visit(dependency, [...path, name])
    }
    state.set(name, 'done')
    ordered.push(name)
  }
  for (const name of Object.keys(schemas).sort()) visit(name, [])
  return ordered
}

export function generateZodModule(document: OpenApiDocument): string {
  const schemas = document.components.schemas
  const blocks = dependencyOrder(schemas).map((name) => {
    const schema = schemas[name]!
    const constName = schemaConstName(name)
    return (
      `${docComment(schema.description, '')}` +
      `export const ${constName} = ${zodExpression(schema)}\n` +
      `export type ${name} = z.infer<typeof ${constName}>\n`
    )
  })
  return `${HEADER}\n${blocks.join('\n')}`
}
